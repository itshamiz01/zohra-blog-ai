@pytest.mark.asyncio
async def test_end_to_end_article_image_pipeline_heavenly():
    """
    Test complete lifecycle with Heavenly Insights target:
    - Prepares publication payload with featured image
    - Generates WebP image, content hash, and SEO filename
    - Renders accessible HTML with width/height/fetchpriority
    - Passes image_url to HeavenlyClient
    """
    site_id = uuid.uuid4()
    site_data = {
        "id": site_id,
        "name": "Heavenly Insights Educator",
        "domain": "heavenly-insights-educator.example.com",
        "niche": "Education & AI",
        "publisher_type": "heavenly",
        "publishing_enabled": True,
        "autonomous_publishing_enabled": True,
        "max_posts_per_day": 5,
        "minimum_publish_interval_minutes": 60,
    }

    draft_data = {
        "id": uuid.uuid4(),
        "version_id": uuid.uuid4(),
        "title": "Mastering Critical Thinking in the Age of Generative AI",
        "primary_topic": "AI in Education",
        "primary_keyword": "ai critical thinking",
        "full_text": "Generative AI is changing how students outline essays. Critical thinking remains irreplaceable.",
        "sections": [
            {"heading": "The Rise of Cognitive Delegation", "body": "Students often turn to AI for instant outlines."},
            {"heading": "Preserving Human Judgment", "body": "Frameworks for validating AI outputs actively."},
        ],
        "faqs": [
            {"question": "Does AI reduce thinking?", "answer": "Only if used uncritically without synthesis."}
        ],
    }

    from app.audit.parser.content_parser import ContentParser
    from app.audit.security.token import AuditTokenManager

    audit_id = str(uuid.uuid4())
    content_hash_val = ContentParser.compute_content_hash(draft_data["full_text"])
    fingerprint = AuditTokenManager.generate_audit_fingerprint(content_hash_val, 1)
    token = AuditTokenManager.sign_audit_token(audit_id, content_hash_val, fingerprint, "PASS")

    audit_data = {
        "audit_id": audit_id,
        "decision": "PASS",
        "eligible_for_part7": True,
        "content_hash": content_hash_val,
        "audit_token": token,
        "audit_fingerprint": fingerprint,
    }

    # 1. Prepare publication payload
    prepared = await PublishingPipeline.prepare_publication_payload(
        final_audit_package_data=audit_data,
        draft_project_data=draft_data,
        site_data=site_data,
        publication_mode=PublicationMode.DRAFT,
    )

    assert "featured_image_bytes" in prepared
    assert len(prepared["featured_image_bytes"]) > 0
    assert "featured_image_filename" in prepared
    assert prepared["featured_image_filename"].endswith(".webp")
    assert "featured_image_url" in prepared
    assert "zohra-featured-media" in prepared["rendered_html"]
    assert 'fetchpriority="high"' in prepared["rendered_html"]

    # Check schema packaging includes featured image
    schema_graph = prepared["schema_package"].get("@graph", [])
    assert any("image" in item for item in schema_graph)

    # 2. Execute publication to Heavenly Insights
    published_cover_url = (
        "https://heavenly-insights-educator.example.com/api/images/abc-123"
    )
    mock_heavenly = AsyncMock(spec=HeavenlyClient)
    mock_heavenly.ensure_public_cover_url.return_value = published_cover_url
    mock_heavenly.create_or_update_post.return_value = {
        "id": 101,
        "slug": prepared["slug"],
        "url": f"https://heavenly-insights-educator.example.com/posts/{prepared['slug']}",
        "status": "published",
    }

    published_package = await PublishingPipeline.execute_publication(
        site_data=site_data,
        prepared_payload=prepared,
        draft_project_data=draft_data,
        final_audit_package_data=audit_data,
        heavenly_client=mock_heavenly,
        posts_published_today=0,
    )

    assert published_package.verification.get("verified") is True
    assert published_package.publisher_target == "heavenly"

    # The generated bytes must be uploaded, and the PUBLIC url published.
    mock_heavenly.ensure_public_cover_url.assert_awaited_once()
    mock_heavenly.create_or_update_post.assert_awaited_once()
    _, kwargs = mock_heavenly.create_or_update_post.call_args
    assert kwargs.get("image_url") == published_cover_url
    assert kwargs.get("cover_image_alt")
    # Regression guard: never publish the local /storage path as the cover.
    assert not str(kwargs.get("image_url")).startswith("/storage/")
    assert published_package.media.get("featured_image_url") == published_cover_url


@pytest.mark.asyncio
async def test_end_to_end_article_image_pipeline_wordpress():
    """
    Test complete lifecycle with WordPress target:
    - Prepares publication payload
    - Uploads media to WordPress via wp_client.upload_media
    - Attaches media ID to post payload (featured_media=media_id)
    - Verifies published post
    """
    site_id = uuid.uuid4()
    site_data = {
        "id": site_id,
        "name": "Tech Horizons",
        "domain": "techhorizons.example.com",
        "wordpress_base_url": "https://techhorizons.example.com",
        "wordpress_api_url": "https://techhorizons.example.com/wp-json",
        "credential_ref": "wp-creds-1",
        "niche": "Artificial Intelligence",
        "publisher_type": "wordpress",
        "publishing_enabled": True,
        "autonomous_publishing_enabled": True,
        "max_posts_per_day": 5,
        "minimum_publish_interval_minutes": 60,
    }

    draft_data = {
        "id": uuid.uuid4(),
        "version_id": uuid.uuid4(),
        "title": "Autonomous Agent Architecture in 2026",
        "primary_topic": "Agentic AI",
        "primary_keyword": "autonomous agents",
        "full_text": "Autonomous agents represent the frontier of scalable software development.",
        "sections": [
            {"heading": "Decentralized Subagents", "body": "Coordination through reactive message queues."},
        ],
    }

    audit_id2 = str(uuid.uuid4())
    content_hash_val2 = ContentParser.compute_content_hash(draft_data["full_text"])
    fingerprint2 = AuditTokenManager.generate_audit_fingerprint(content_hash_val2, 1)
    token2 = AuditTokenManager.sign_audit_token(audit_id2, content_hash_val2, fingerprint2, "PASS")

    audit_data = {
        "audit_id": audit_id2,
        "decision": "PASS",
        "eligible_for_part7": True,
        "content_hash": content_hash_val2,
        "audit_token": token2,
        "audit_fingerprint": fingerprint2,
    }

    prepared = await PublishingPipeline.prepare_publication_payload(
        final_audit_package_data=audit_data,
        draft_project_data=draft_data,
        site_data=site_data,
        publication_mode=PublicationMode.DRAFT,
    )

    mock_wp = AsyncMock(spec=WordPressClient)
    mock_wp.upload_media.return_value = {
        "id": 999,
        "source_url": "https://techhorizons.example.com/wp-content/uploads/featured.webp",
    }
    mock_wp.list_categories.return_value = [{"id": 1, "name": "AI", "slug": "ai"}]
    mock_wp.list_tags.return_value = []
    mock_wp.create_post.return_value = {
        "id": 501,
        "title": {"rendered": prepared["title"]},
        "status": "draft",
        "link": f"https://techhorizons.example.com/{prepared['slug']}",
        "slug": prepared["slug"],
        "featured_media": 999,
        "content": {"rendered": prepared["rendered_html"]},
    }

    published_package = await PublishingPipeline.execute_publication(
        site_data=site_data,
        prepared_payload=prepared,
        draft_project_data=draft_data,
        final_audit_package_data=audit_data,
        wp_client=mock_wp,
        posts_published_today=0,
    )

    assert published_package.verification.get("verified") is True
    assert published_package.media.get("featured_media_id") == 999
    mock_wp.upload_media.assert_awaited_once()
    mock_wp.create_post.assert_awaited_once()
    create_args, _ = mock_wp.create_post.call_args
    assert create_args[0].get("featured_media") == 999
